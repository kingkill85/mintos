// uses: frontend/inputmap.c
#include <string.h>
#include "check.h"
#include "inputmap.h"

int main(void) {
    /* Nintendo layout: SDL names by position, the RG353V prints A on the right */
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_A), RETRO_DEVICE_ID_JOYPAD_B);   /* bottom */
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_B), RETRO_DEVICE_ID_JOYPAD_A);   /* right */
    /* SDL maps BTN_NORTH->x, BTN_WEST->y for this pad (checked on the device), so X/Y match the labels */
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_X), RETRO_DEVICE_ID_JOYPAD_X);   /* top */
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_Y), RETRO_DEVICE_ID_JOYPAD_Y);   /* left */
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_LEFTSHOULDER), RETRO_DEVICE_ID_JOYPAD_L);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_RIGHTSHOULDER), RETRO_DEVICE_ID_JOYPAD_R);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_LEFTSTICK), RETRO_DEVICE_ID_JOYPAD_L3);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_RIGHTSTICK), RETRO_DEVICE_ID_JOYPAD_R3);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_BACK), RETRO_DEVICE_ID_JOYPAD_SELECT);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_START), RETRO_DEVICE_ID_JOYPAD_START);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_DPAD_UP), RETRO_DEVICE_ID_JOYPAD_UP);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_DPAD_DOWN), RETRO_DEVICE_ID_JOYPAD_DOWN);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_DPAD_LEFT), RETRO_DEVICE_ID_JOYPAD_LEFT);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_DPAD_RIGHT), RETRO_DEVICE_ID_JOYPAD_RIGHT);
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_GUIDE), -1);   /* F opens the menu */
    CHECK_INT(map_button(SDL_CONTROLLER_BUTTON_MISC1), -1);
    /* triggers are axes */
    CHECK_INT(map_trigger(SDL_CONTROLLER_AXIS_TRIGGERLEFT), RETRO_DEVICE_ID_JOYPAD_L2);
    CHECK_INT(map_trigger(SDL_CONTROLLER_AXIS_TRIGGERRIGHT), RETRO_DEVICE_ID_JOYPAD_R2);
    CHECK_INT(map_trigger(SDL_CONTROLLER_AXIS_LEFTX), -1);
    TEST_END();
}
